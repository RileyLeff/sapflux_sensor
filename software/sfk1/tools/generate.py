sys.path.insert(0, str(ANALYSIS))

import common as C  # noqa: E402
import encoder_spec as S  # noqa: E402

STRIDE = 29  # decoded-sample stride stored in the vectors (prime: hits every phase)


def windows() -> list[C.Window]:
    corpus = C.load_corpus()
    quiet = next(w for w in corpus if w.regime == "quiet")
    interf = next(w for w in corpus if w.regime == "interference")
    return C.real_pulses() + [quiet, interf]


