#!/usr/bin/env python3
"""Generate the sfk1 crate's constant tables and golden test vectors.

Everything comes from the research reference
(analysis/compression_research_20261024/encoder_spec.py): the firmware mode
`encode(w, fixed_point="firmware")` defines the integer arithmetic the Rust
encoder must reproduce byte for byte, and `decode` is the float decoder the
Rust decoder is checked against.

    cd analysis/compression_research_20261024
    uv run --with numpy --with scipy --with pandas --with matplotlib \
        python ../../software/sfk1/tools/generate.py            # tables + vectors
    ... generate.py --check-record FILE --window NAME --knots 12    # decode a Rust-made record
    ... generate.py --profile probe48_10hz --period-us 100000 --knots 12   # tables for a custom Profile

Outputs:

* src/tables.rs: log2 polynomial, knot scale, B-spline pieces, the i32
  encoder matrix, the Rice k-tables and the f64 decoder matrix.
* --profile NAME: tests/profiles/NAME.rs, the trained tables (KF_Q28,
  K_TABLE, MQ, D) of a custom `sfk1::Profile` with another frame period,
  window length, t0, knot count or step, from the same physics training
  as the East30 tables (encoders.klt_rotation / rice_k_table).
* tests/vectors/*.sfkv: per window, the raw nominal-grid frames (with
  missing slots) plus records and what decoding them must give.

Vector file layout (little endian):

    "SFKV" u8 format=1
    u8 name_len, name (utf-8)
    u16 live_mask, u8 n_bins, u16 n_frames
    presence bitmap, ceil(n_frames / 8) bytes, frame k = bit (k & 7) of byte k >> 3
    for each present frame: 13 x zigzag LEB128 varint of (value - previous
        present frame's value), channel 0 = excitation; "previous" starts at 0
    u8 n_records, then per record:
        u8 kind (0 = firmware mode: the Rust encoder must produce these bytes,
                 1 = float reference mode: decode only)
        u8 knots, u8 flags (bit 0: decoded samples follow), u16 missing frames
        u16 len, record bytes
        per live channel: n_bins x i32 baseline bins, n_coefs x i32 coefficients
        if flags & 1: u16 stride, then per live channel the Python decoder's
            f64 output at frames 0, stride, 2 stride, ... (< the record's n_frames)
"""

from __future__ import annotations

import argparse
import json
import struct
import sys
from pathlib import Path

import numpy as np

CRATE = Path(__file__).resolve().parents[1]
ANALYSIS = CRATE.parents[1] / "analysis/compression_research_20261024"
sys.path.insert(0, str(ANALYSIS))

import common as C  # noqa: E402
import encoder_spec as S  # noqa: E402

STRIDE = 29  # decoded-sample stride stored in the vectors (prime: hits every phase)


def windows() -> list[C.Window]:
    corpus = C.load_corpus()
    quiet = next(w for w in corpus if w.regime == "quiet")
    interf = next(w for w in corpus if w.regime == "interference")
    return C.real_pulses() + [quiet, interf]


# --------------------------------------------------------------------------
# tables.rs


def rust_tables() -> str:
    consts = json.loads((ANALYSIS / "results/encoder_constants.json").read_text())
    out = [
        "// @generated by tools/generate.py from analysis/compression_research_20261024",
        "// (encoder_spec.py firmware mode + results/encoder_constants.json). Do not edit.",
        "",
        "/// `log2(1 + f)` for `f` in `[0, 1)`, Q30, lowest power first (Horner).",
        f"pub(crate) const LOG2_POLY: [i64; {len(S.FW_LOG2_POLY)}] = {list(S.FW_LOG2_POLY)};",
        "",
        "/// Cubic B-spline pieces x 12 on the five interval kinds (first, second,",
        "/// interior, second-last, last); `[kind][m][power]` is basis `i + m` on",
        "/// interval `i`, in the local coordinate `x` in `[0, 1]`.",
        "pub(crate) const BASIS_C12: [[[i8; 4]; 4]; 5] = [",
    ]
    for kind in S.FW_BASIS_C12:
        out.append("    [" + ", ".join("[" + ", ".join(str(v) for v in row) + "]" for row in kind) + "],")
    out.append("];")
    for knots in (12, 16):
        n = knots + 4
        mq = S.fw_matrix(knots)
        kt = S.fw_k_table(knots)
        D = consts[str(knots)]["D_dec_16x16"]
        assert all(abs(v) < 2**31 for row in mq for v in row)
        rs = max(sum(abs(v) for v in row) for row in mq)
        assert rs * 2**31 < 2**63, "M row sum bound"
        out += [
            "",
            f"/// `K ln 2 / (ln 183 + 1e-9 - ln 2)` in Q28 for {knots} interior knots.",
            f"pub(crate) const KF_K{knots}: i64 = {S.FW_KF_Q28[knots]};",
            f"/// Rice k-table, {knots} knots.",
            f"pub(crate) const K_TABLE_K{knots}: [u8; {n}] = {list(kt)};",
            f"/// Encoder matrix `round(M * 2^36 / 576)`, {knots} knots, row-major",
            f"/// (row sums of |Mq| <= {rs}, so `sum(Mq * gx)` with |gx| < 2^31 cannot overflow).",
            f"pub(crate) const MQ_K{knots}: [[i32; {n}]; {n}] = [",
        ]
        out += ["    [" + ", ".join(str(v) for v in row) + "]," for row in mq]
        out += [
            "];",
            f"/// Decoder matrix `D = R^-1 V`, {knots} knots, row-major.",
            f"pub(crate) const D_K{knots}: [[f64; {n}]; {n}] = [",
        ]
        out += ["    [" + ", ".join(repr(float(v)) for v in row) + "]," for row in D]
        out.append("];")
    return "\n".join(out) + "\n"


def profile_tables(name: str, period_us: int, post_s: float, t0: float, knots: int, step: float) -> str:
    """Trained tables of a custom profile, as Rust consts for `include!`.

    Same recipe as encoder_spec.constants() for East30, on the profile's own
    grid t = 0, period, ..., post_s: B = cubic B-splines in ln(t + t0), R from
    QR(B), V = the physics-trained KLT rotation, M = V^T R^-T, D = R^-1 V;
    MQ = round(M 2^36 / (192 step)); the Rice k-table from the training
    curves at noise sigma_ref / step."""
    import encoders as E

    n_post = int(round(post_s * 1e6 / period_us)) + 1
    t = np.arange(n_post) * period_us / 1e6
    key = tuple(np.round(t, 4))
    B = E.post_spline_basis(t, knots, t0)
    _, R = np.linalg.qr(B)
    V = E.klt_rotation(key, knots, t0, 1.0)
    M = V.T @ np.linalg.inv(R).T
    D = np.linalg.inv(R) @ V
    kt = E.rice_k_table(key, knots, t0, 1.0, step / E.SIGMA_REF)
    mq = np.round(M * 2.0**S.FW_M_SHIFT / (192 * step)).astype(np.int64)
    assert np.abs(mq).max() < 2**31
    span = np.log(t[-1] + t0) + 1e-9 - np.log(t0)
    kf = int(round(2**28 * (knots + 1) * np.log(2) / span))
    t0f = t0 * 1e6 / period_us
    assert abs(t0f - round(t0f)) < 1e-9, "t0 must be a whole number of frames"
    n = knots + 4
    out = [
        f"// @generated by tools/generate.py --profile {name} --period-us {period_us} --post-s {post_s} --t0 {t0} --knots {knots} --step {step}",
        "// Trained tables for a custom sfk1::Profile. Do not edit.",
        f"// Profile constants to match: FRAME_PERIOD_US = {period_us}, POST_FRAMES = {n_post}, T0_FRAMES = {int(round(t0f))},",
        f"// KNOTS = {knots}, STEP = {step}, Acc = [i64; {n}].",
        "",
        "/// Knot scale, Q28.",
        f"pub const KF_Q28: i64 = {kf};",
        "/// Rice k-table.",
        f"pub const K_TABLE: [u8; {n}] = {list(kt)};",
        "/// Encoder matrix `round(M 2^36 / (192 STEP))`.",
        f"pub const MQ: [[i32; {n}]; {n}] = [",
    ]
    out += ["    [" + ", ".join(str(int(v)) for v in row) + "]," for row in mq]
    out += ["];", "/// Decoder matrix `D = R^-1 V`.", f"pub const D: [[f64; {n}]; {n}] = ["]
    out += ["    [" + ", ".join(repr(float(v)) for v in row) + "]," for row in D]
    out.append("];")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# vectors


def varint(u: int) -> bytes:
    b = bytearray()
    while True:
        x = u & 0x7F
        u >>= 7
        if u:
            b.append(x | 0x80)
        else:
            b.append(x)
            return bytes(b)


def zz(v: int) -> int:
    return 2 * v if v >= 0 else -2 * v - 1


def vector_file(w: C.Window) -> tuple[bytes, dict]:
    raw, present, live, nb = S.fw_frames(w)
    n = len(present)
    mask = sum(1 << (c - 1) for c in live)
    name = w.name.encode()
    out = bytearray(b"SFKV" + bytes([1, len(name)]) + name + struct.pack("<HBH", mask, nb, n))
    bm = bytearray((n + 7) // 8)
    for k in np.flatnonzero(present):
        bm[k >> 3] |= 1 << (k & 7)
    out += bm
    prev = [0] * C.N_CH
    for k in np.flatnonzero(present):
        for c in range(C.N_CH):
            v = int(raw[k, c])
            out += varint(zz(v - prev[c]))
            prev[c] = v
    records = []
    info = {}
    for knots in (12, 16):
        data, enc = S.encode(w, "firmware", knots)
        records.append((0, knots, enc["missing"], data, enc, S.fw_time(enc["nb"])))
        info[f"firmware_k{knots}"] = {"bytes": len(data), "missing": enc["missing"], "e_ref": enc["e_ref"]}
        fdata, fenc = S.encode(w, knots=knots)
        nominal = w.kind == "synthetic"  # corpus windows are on the nominal grid already
        records.append((1, knots, 0, fdata, fenc, S.fw_time(len(fenc["base"][live[0]])) if nominal else None))
        info[f"float_k{knots}"] = {"bytes": len(fdata)}
    out.append(len(records))
    for kind, knots, missing, data, enc, tdec in records:
        out += struct.pack("<BBBHH", kind, knots, 1 if tdec is not None else 0, missing, len(data)) + data
        # the reference decoder must recover exactly the integers that were written
        t_int = tdec if tdec is not None else w.t
        recon, dec = S.decode(data, t_int)
        for c in live:
            assert np.array_equal(dec["base"][c], enc["base"][c]) and np.array_equal(dec["coefs"][c], enc["coefs"][c])
            out += struct.pack(f"<{len(enc['base'][c])}i", *enc["base"][c].tolist())
            out += struct.pack(f"<{len(enc['coefs'][c])}i", *enc["coefs"][c].tolist())
        if tdec is not None:
            out += struct.pack("<H", STRIDE)
            for c in live:
                out += struct.pack(f"<{len(range(0, len(tdec), STRIDE))}d", *recon[::STRIDE, c].tolist())
    return bytes(out), info


def check_record(path: Path, window: str, knots: int) -> None:
    """Decode a record produced by the Rust encoder and compare it with this
    reference's own firmware-mode encoding of the same window."""
    w = next(x for x in windows() if x.name == window)
    data = path.read_bytes()
    ref, enc = S.encode(w, "firmware", knots)
    recon, dec = S.decode(data, S.fw_time(enc["nb"]))
    same = all(np.array_equal(dec["base"][c], enc["base"][c]) and np.array_equal(dec["coefs"][c], enc["coefs"][c]) for c in w.live)
    print(f"{path.name}: {len(data)} B, Python decode ok, integers match firmware mode: {same}, bytes identical: {data == ref}")
    if not same:
        raise SystemExit(1)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check-record", type=Path)
    ap.add_argument("--window", default="real_aug24_soaked4x4")
    ap.add_argument("--knots", type=int, default=12)
    ap.add_argument("--profile", help="write tests/profiles/PROFILE.rs (custom profile tables) and exit")
    ap.add_argument("--period-us", type=int, default=40_000, help="frame period, microseconds (40000 = 25 Hz)")
    ap.add_argument("--post-s", type=float, default=181.0)
    ap.add_argument("--t0", type=float, default=2.0)
    ap.add_argument("--step", type=float, default=3.0)
    args = ap.parse_args()
    if args.profile:
        path = CRATE / "tests/profiles" / f"{args.profile}.rs"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(profile_tables(args.profile, args.period_us, args.post_s, args.t0, args.knots, args.step))
        print(f"wrote {path}")
        return
    if args.check_record:
        check_record(args.check_record, args.window, args.knots)
        return
    (CRATE / "src/tables.rs").write_text(rust_tables())
    vec_dir = CRATE / "tests/vectors"
    vec_dir.mkdir(parents=True, exist_ok=True)
    total = 0
    manifest = {}
    for w in windows():
        blob, info = vector_file(w)
        (vec_dir / f"{w.name}.sfkv").write_bytes(blob)
        total += len(blob)
        manifest[w.name] = {"file_bytes": len(blob), **info}
        print(f"{w.name:24s} {len(blob):7d} B  {info}")
    (vec_dir / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print(f"total {total} B")


if __name__ == "__main__":
    main()
