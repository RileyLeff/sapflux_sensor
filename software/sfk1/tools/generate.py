#!/usr/bin/env python3
"""Generate the sfk1 crate's constant tables and golden test vectors.

Everything comes from the research reference
(analysis/compression_research_20261024/encoder_spec.py): the firmware mode
`encode(w, fixed_point="firmware")` defines the integer arithmetic the Rust
encoder must reproduce byte for byte, and `decode` is the float decoder the
Rust decoder is checked against.

    cd analysis/compression_research_20261024
    uv run --with numpy --with scipy --with pandas --with matplotlib \
        python ../../software/sfk1/tools/generate.py            # tables + vectors
    ... generate.py --check-record FILE --window NAME --knots 12    # decode a Rust-made record
    ... generate.py --profile probe48_10hz --period-us 100000 --knots 12   # tables for a custom Profile
    ... generate.py --profile east30_1cm --struct East30At1cm --positions='1,0 -1,0'   # another spacing

Outputs:

* src/tables.rs: log2 polynomial, knot scale, B-spline pieces, the i32
  encoder matrix, the Rice k-tables and the f64 decoder matrix.
* --profile NAME: tests/profiles/NAME.rs (or --out), the trained tables
  (KF_Q28, K_TABLE, MQ, D) of a custom `sfk1::Profile` for its own frame
  period, window, t0, knots, step, thermistor positions and physics priors;
  with --struct, also a ready `impl sfk1::Profile`. Training simulates
  heat pulses at the given positions (see train_tables).
* tests/vectors/*.sfkv: per window, the raw nominal-grid frames (with
  missing slots) plus records and what decoding them must give.

Vector file layout (little endian):

    "SFKV" u8 format=1
    u8 name_len, name (utf-8)
    u16 live_mask, u8 n_bins, u16 n_frames
    presence bitmap, ceil(n_frames / 8) bytes, frame k = bit (k & 7) of byte k >> 3
    for each present frame: 13 x zigzag LEB128 varint of (value - previous
        present frame's value), channel 0 = excitation; "previous" starts at 0
    u8 n_records, then per record:
        u8 kind (0 = firmware mode: the Rust encoder must produce these bytes,
                 1 = float reference mode: decode only)
        u8 knots, u8 flags (bit 0: decoded samples follow), u16 missing frames
        u16 len, record bytes
        per live channel: n_bins x i32 baseline bins, n_coefs x i32 coefficients
        if flags & 1: u16 stride, then per live channel the Python decoder's
            f64 output at frames 0, stride, 2 stride, ... (< the record's n_frames)
"""

