# vectors


def varint(u: int) -> bytes:
    b = bytearray()
    while True:
        x = u & 0x7F
        u >>= 7
        if u:
            b.append(x | 0x80)
        else:
            b.append(x)
            return bytes(b)


def zz(v: int) -> int:
    return 2 * v if v >= 0 else -2 * v - 1


def vector_file(w: C.Window) -> tuple[bytes, dict]:
    raw, present, live, nb = S.fw_frames(w)
    n = len(present)
    mask = sum(1 << (c - 1) for c in live)
    name = w.name.encode()
    out = bytearray(b"SFKV" + bytes([1, len(name)]) + name + struct.pack("<HBH", mask, nb, n))
    bm = bytearray((n + 7) // 8)
    for k in np.flatnonzero(present):
        bm[k >> 3] |= 1 << (k & 7)
    out += bm
    prev = [0] * C.N_CH
    for k in np.flatnonzero(present):
        for c in range(C.N_CH):
            v = int(raw[k, c])
            out += varint(zz(v - prev[c]))
            prev[c] = v
    records = []
    info = {}
    for knots in (12, 16):
        data, enc = S.encode(w, "firmware", knots)
        records.append((0, knots, enc["missing"], data, enc, S.fw_time(enc["nb"])))
        info[f"firmware_k{knots}"] = {"bytes": len(data), "missing": enc["missing"], "e_ref": enc["e_ref"]}
        fdata, fenc = S.encode(w, knots=knots)
        nominal = w.kind == "synthetic"  # corpus windows are on the nominal grid already
        records.append((1, knots, 0, fdata, fenc, S.fw_time(len(fenc["base"][live[0]])) if nominal else None))
        info[f"float_k{knots}"] = {"bytes": len(fdata)}
    out.append(len(records))
    for kind, knots, missing, data, enc, tdec in records:
        out += struct.pack("<BBBHH", kind, knots, 1 if tdec is not None else 0, missing, len(data)) + data
        # the reference decoder must recover exactly the integers that were written
        t_int = tdec if tdec is not None else w.t
        recon, dec = S.decode(data, t_int)
        for c in live:
            assert np.array_equal(dec["base"][c], enc["base"][c]) and np.array_equal(dec["coefs"][c], enc["coefs"][c])
            out += struct.pack(f"<{len(enc['base'][c])}i", *enc["base"][c].tolist())
            out += struct.pack(f"<{len(enc['coefs'][c])}i", *enc["coefs"][c].tolist())
        if tdec is not None:
            out += struct.pack("<H", STRIDE)
            for c in live:
                out += struct.pack(f"<{len(range(0, len(tdec), STRIDE))}d", *recon[::STRIDE, c].tolist())
    return bytes(out), info


def check_record(path: Path, window: str, knots: int) -> None:
    """Decode a record produced by the Rust encoder and compare it with this
    reference's own firmware-mode encoding of the same window."""
    w = next(x for x in windows() if x.name == window)
    data = path.read_bytes()
    ref, enc = S.encode(w, "firmware", knots)
    recon, dec = S.decode(data, S.fw_time(enc["nb"]))
    same = all(np.array_equal(dec["base"][c], enc["base"][c]) and np.array_equal(dec["coefs"][c], enc["coefs"][c]) for c in w.live)
    print(f"{path.name}: {len(data)} B, Python decode ok, integers match firmware mode: {same}, bytes identical: {data == ref}")
    if not same:
        raise SystemExit(1)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check-record", type=Path)
    ap.add_argument("--window", default="real_aug24_soaked4x4")
    ap.add_argument("--knots", type=int, default=12)
    ap.add_argument("--profile", help="write tests/profiles/PROFILE.rs (custom profile tables) and exit")
    ap.add_argument("--period-us", type=int, default=40_000, help="frame period, microseconds (40000 = 25 Hz)")
    ap.add_argument("--post-s", type=float, default=181.0)
    ap.add_argument("--t0", type=float, default=2.0)
    ap.add_argument("--step", type=float, default=3.0)
    ap.add_argument("--bin-s", type=float, default=5.0, help="baseline bin length, s")
    ap.add_argument("--max-bins", type=int, default=12, help="most baseline bins (Profile::Bins length)")
    ap.add_argument("--struct", help="also emit `pub struct STRUCT` and its impl sfk1::Profile")
    ap.add_argument("--out", type=Path, help="output file (default tests/profiles/PROFILE.rs)")
    ap.add_argument("--positions", default="0.6,0 -0.6,0", metavar="'X,Y X,Y ...'",
                    help="thermistor positions relative to the heater, cm, x along the expected flow; "
                    "write --positions='1,0 -1,0' (with '=') when the first starts with a minus")
    ph = Physics()
    ap.add_argument("--k-range", type=float, nargs=2, default=ph.k_cm2_s, help="thermal diffusivity, cm^2/s")
    ap.add_argument("--v-range", type=float, nargs=2, default=ph.v_cm_h, help="heat-pulse velocity, cm/h")
    ap.add_argument("--flow-angle-deg", type=float, default=ph.flow_angle_deg,
                    help="flow direction drawn within +-this of +x")
    ap.add_argument("--pulse-s", type=float, default=ph.pulse_s)
    ap.add_argument("--spacing-error", type=float, default=ph.spacing_error, help="radial, fraction")
    ap.add_argument("--lateral-error-cm", type=float, default=ph.lateral_error_cm)
    ap.add_argument("--peak-counts", type=float, nargs=2, default=ph.peak_counts,
                    help="pulse peak at --peak-at-cm downstream with no flow, counts")
    ap.add_argument("--peak-at-cm", type=float, default=ph.peak_at_cm)
    args = ap.parse_args()
    if args.profile:
        positions = tuple(tuple(float(v) for v in p.split(",")) for p in args.positions.split())
        assert all(len(p) == 2 and np.hypot(*p) > 0 for p in positions), "positions are X,Y pairs off the heater"
        phys = Physics(
            k_cm2_s=tuple(args.k_range), v_cm_h=tuple(args.v_range), flow_angle_deg=args.flow_angle_deg,
            pulse_s=args.pulse_s, spacing_error=args.spacing_error, lateral_error_cm=args.lateral_error_cm,
            peak_counts=tuple(args.peak_counts), peak_at_cm=args.peak_at_cm,
        )
        path = args.out or CRATE / "tests/profiles" / f"{args.profile}.rs"
        path.parent.mkdir(parents=True, exist_ok=True)
        command = shlex.join(sys.argv[1:])
        path.write_text(profile_tables(args.profile, args.period_us, args.post_s, args.t0, args.knots, args.step,
                                       positions, phys, args.struct, args.bin_s, args.max_bins, command))
        print(f"wrote {path}")
        return
    if args.check_record:
        check_record(args.check_record, args.window, args.knots)
        return
    (CRATE / "src/tables.rs").write_text(rust_tables())
    vec_dir = CRATE / "tests/vectors"
    vec_dir.mkdir(parents=True, exist_ok=True)
    total = 0
    manifest = {}
    for w in windows():
        blob, info = vector_file(w)
        (vec_dir / f"{w.name}.sfkv").write_bytes(blob)
        total += len(blob)
        manifest[w.name] = {"file_bytes": len(blob), **info}
        print(f"{w.name:24s} {len(blob):7d} B  {info}")
    (vec_dir / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print(f"total {total} B")


if __name__ == "__main__":
    main()
