use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const LOCAL_CONFIG: &str = "gateway.local.toml";
const EXAMPLE_CONFIG: &str = "gateway.example.toml";

struct GatewayConfig {
    server_ip: [u8; 4],
    server_port: u16,
    device_id: u64,
    key: [u8; 32],
}

fn main() {
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by Cargo"));
    fs::copy("memory.x", out.join("memory.x")).expect("copy memory.x");

    println!("cargo:rustc-link-search={}", out.display());
    println!("cargo:rerun-if-changed=memory.x");
    println!("cargo:rerun-if-env-changed=SAPFLUX_GATEWAY_CONFIG");
    println!("cargo:rerun-if-changed={LOCAL_CONFIG}");
    println!("cargo:rerun-if-changed={EXAMPLE_CONFIG}");

    let (path, is_example) = match env::var_os("SAPFLUX_GATEWAY_CONFIG") {
        Some(p) => (PathBuf::from(p), false),
        None if Path::new(LOCAL_CONFIG).exists() => (PathBuf::from(LOCAL_CONFIG), false),
        None => {
            println!(
                "cargo:warning=no {LOCAL_CONFIG}; building with {EXAMPLE_CONFIG} \
                 (placeholder server and key, not deployable)"
            );
            (PathBuf::from(EXAMPLE_CONFIG), true)
        }
    };
    println!("cargo:rerun-if-changed={}", path.display());

    let text = fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("read gateway config {}: {e}", path.display()));
    let config = parse(&text).unwrap_or_else(|e| panic!("gateway config {}: {e}", path.display()));

    let generated = format!(
        "// Generated by build.rs from {path}. Do not edit.\n\
         /// Server IPv4 address.\n\
         pub const SERVER_IP: [u8; 4] = {ip:?};\n\
         /// Server UDP port.\n\
         pub const SERVER_PORT: u16 = {port};\n\
         /// Device id override; 0 = derive from the IMEI.\n\
         pub const DEVICE_ID_OVERRIDE: u64 = {device_id};\n\
         /// HMAC-SHA256 key shared with the server.\n\
         pub const KEY: [u8; 32] = {key:?};\n\
         /// True when built from the committed example file.\n\
         pub const IS_EXAMPLE: bool = {is_example};\n",
        path = path.display(),
        ip = config.server_ip,
        port = config.server_port,
        device_id = config.device_id,
        key = config.key,
    );
    fs::write(out.join("gateway_config.rs"), generated).expect("write gateway_config.rs");
}

fn parse(text: &str) -> Result<GatewayConfig, String> {
    let mut server_ip = None;
    let mut server_port = None;
    let mut device_id = None;
    let mut key = None;

    for (n, raw) in text.lines().enumerate() {
        let line = strip_comment(raw).trim();
        if line.is_empty() {
            continue;
        }
        let (k, v) = line
            .split_once('=')
            .ok_or_else(|| format!("line {}: expected key = value", n + 1))?;
        let k = k.trim();
        let v = v.trim();
        let err = |what: &str| format!("line {}: {k}: {what}", n + 1);
        match k {
            "server_ip" => {
                let s = unquote(v).ok_or_else(|| err("expected a quoted string"))?;
                let ip: std::net::Ipv4Addr = s.parse().map_err(|_| err("not an IPv4 literal"))?;
                server_ip = Some(ip.octets());
            }
            "server_port" => {
                let p: u16 = v.parse().map_err(|_| err("expected 1..65535"))?;
                if p == 0 {
                    return Err(err("port 0"));
                }
                server_port = Some(p);
            }
            "device_id" => {
                device_id = Some(v.parse::<u64>().map_err(|_| err("expected an unsigned integer"))?);
            }
            "key" => {
                let s = unquote(v).ok_or_else(|| err("expected a quoted string"))?;
                if s.len() != 64 {
                    return Err(err("expected 64 hex digits (32 bytes)"));
                }
                let mut bytes = [0u8; 32];
                for (i, b) in bytes.iter_mut().enumerate() {
                    *b = u8::from_str_radix(&s[2 * i..2 * i + 2], 16).map_err(|_| err("bad hex"))?;
                }
                key = Some(bytes);
            }
            other => return Err(format!("line {}: unknown key {other}", n + 1)),
        }
    }

    Ok(GatewayConfig {
        server_ip: server_ip.ok_or("missing server_ip")?,
        server_port: server_port.ok_or("missing server_port")?,
        device_id: device_id.ok_or("missing device_id")?,
        key: key.ok_or("missing key")?,
    })
}

fn strip_comment(line: &str) -> &str {
    // No key value contains '#', so the first '#' starts a comment.
    match line.find('#') {
        Some(i) => &line[..i],
        None => line,
    }
}

fn unquote(v: &str) -> Option<&str> {
    v.strip_prefix('"')?.strip_suffix('"')
}
